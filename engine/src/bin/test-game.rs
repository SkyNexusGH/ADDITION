//! A tiny stand-in "game" for trying ADDITION out and for the engine's
//! integration tests. It keeps its state the way real games do: a static
//! pointer in the executable leads to a heap-allocated world, which points to
//! the player.
//!
//! Type commands (`hit`, `shoot`, `spend 50`, `respawn`, `state`, `quit`), or
//! run with `--auto` to take damage every second. Run with `--install-trainer`
//! to write a matching trainer into ADDITION's trainers folder.

use std::io::{BufRead, Write};
use std::sync::atomic::{AtomicUsize, Ordering};

#[repr(C)]
struct Player {
    health: i32, // +0x0
    ammo: i32,   // +0x4
    speed: f32,  // +0x8
    _pad: u32,
    gold: i64, // +0x10
}

#[repr(C)]
struct World {
    _header: [u8; 0x30],
    level: u32,
    _pad: u32,
    player: *mut Player, // +0x38
}

const PLAYER_OFFSET: usize = 0x38;

/// The static pointer every chain starts from. Non-zero initial value keeps
/// it in .data like most engines' globals.
static WORLD: AtomicUsize = AtomicUsize::new(1);

/// Damage per hit lives in read-only data behind a recognizable signature, so
/// a byte-patch cheat can find it and set it to zero.
#[used]
static DAMAGE_RULES: [u8; 12] = [0xAD, 0xD1, 0x71, 0x0E, 0x5E, 0xED, 7, 0x5E, 0xED, 0xAD, 0xD1, 0x00];

fn damage() -> i32 {
    // Volatile so the compiler can't fold the constant into the code.
    unsafe { std::ptr::read_volatile(&DAMAGE_RULES[6]) as i32 }
}

fn world() -> &'static mut World {
    unsafe { &mut *(WORLD.load(Ordering::SeqCst) as *mut World) }
}

fn player() -> &'static mut Player {
    unsafe { &mut *world().player }
}

fn new_player() -> *mut Player {
    // Some heap noise so the player doesn't land at a predictable spot.
    let noise: Vec<Box<[u8; 48]>> = (0..(std::process::id() % 17 + 3)).map(|_| Box::new([0u8; 48])).collect();
    std::mem::forget(noise);
    Box::into_raw(Box::new(Player { health: 100, ammo: 30, speed: 1.0, _pad: 0, gold: 500 }))
}

fn state() -> String {
    let p = player();
    // Volatile reads: an external tool changes these behind the compiler's back.
    unsafe {
        format!(
            "{{\"health\":{},\"ammo\":{},\"speed\":{},\"gold\":{}}}",
            std::ptr::read_volatile(&p.health),
            std::ptr::read_volatile(&p.ammo),
            std::ptr::read_volatile(&p.speed),
            std::ptr::read_volatile(&p.gold)
        )
    }
}

fn addresses() -> String {
    let p = player() as *mut Player as usize;
    format!(
        "{{\"health\":{},\"gold\":{},\"world_static\":{},\"module_base\":{}}}",
        p,
        p + 0x10,
        &WORLD as *const _ as usize,
        module_base()
    )
}

#[cfg(windows)]
fn module_base() -> usize {
    extern "C" {
        static __ImageBase: u8;
    }
    unsafe { &__ImageBase as *const u8 as usize }
}

#[cfg(not(windows))]
fn module_base() -> usize {
    extern "C" {
        static __executable_start: u8;
    }
    unsafe { &__executable_start as *const u8 as usize }
}

fn exe_name() -> String {
    std::env::current_exe()
        .ok()
        .and_then(|p| p.file_name().map(|n| n.to_string_lossy().into_owned()))
        .unwrap_or_else(|| "test-game".into())
}

fn trainer_json() -> String {
    let static_off = &WORLD as *const _ as usize - module_base();
    let exe = exe_name();
    let target = |field: usize| format!(r#"{{ "module": "{exe}", "base": "0x{static_off:X}", "offsets": ["0x{PLAYER_OFFSET:X}", "0x{field:X}"] }}"#);
    format!(
        r#"{{
  "schema": 1,
  "id": "test-game",
  "game": "ADDITION Test Game",
  "process": ["test-game.exe", "test-game"],
  "game_version": "this build",
  "author": "ADDITION",
  "notes": "Generated by test-game --install-trainer. Rebuilding the test game can move its statics, so regenerate after a rebuild.",
  "verified": true,
  "cheats": [
    {{ "id": "health", "name": "Unlimited Health", "kind": "freeze", "type": "i32", "value": 100, "hotkey": "F1",
       "target": {health} }},
    {{ "id": "ammo", "name": "Unlimited Ammo", "kind": "freeze", "type": "i32", "value": 30, "hotkey": "F2",
       "target": {ammo} }},
    {{ "id": "gold", "name": "Set Gold", "kind": "set", "type": "i64", "min": 0, "max": 1000000, "default": 99999, "hotkey": "F3",
       "target": {gold} }},
    {{ "id": "speed", "name": "Move Speed", "kind": "set", "type": "f32", "min": 0.1, "max": 10, "default": 2.5,
       "target": {speed} }},
    {{ "id": "nodamage", "name": "No Damage", "kind": "patch", "hotkey": "F4",
       "description": "Patches the damage table to 0 instead of undoing damage after the fact.",
       "aob": "AD D1 71 0E 5E ED ?? 5E ED AD D1", "offset": 6, "bytes": "00" }}
  ]
}}
"#,
        health = target(0x0),
        ammo = target(0x4),
        gold = target(0x10),
        speed = target(0x8),
    )
}

fn trainers_dir() -> Option<std::path::PathBuf> {
    let base = if cfg!(windows) {
        std::env::var_os("APPDATA").map(std::path::PathBuf::from)
    } else {
        std::env::var_os("XDG_DATA_HOME")
            .map(std::path::PathBuf::from)
            .or_else(|| std::env::var_os("HOME").map(|h| std::path::PathBuf::from(h).join(".local/share")))
    }?;
    Some(base.join("io.addition.app").join("trainers"))
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    WORLD.store(
        Box::into_raw(Box::new(World { _header: [0x57; 0x30], level: 1, _pad: 0, player: new_player() })) as usize,
        Ordering::SeqCst,
    );

    if args.iter().any(|a| a == "--print-trainer") {
        print!("{}", trainer_json());
        return;
    }
    if args.iter().any(|a| a == "--install-trainer") {
        let dir = trainers_dir().expect("could not find the app data folder");
        std::fs::create_dir_all(&dir).expect("create trainers folder");
        let path = dir.join("test-game.json");
        std::fs::write(&path, trainer_json()).expect("write trainer");
        println!("Trainer written to {}", path.display());
        return;
    }

    let auto = args.iter().any(|a| a == "--auto");
    println!("ready pid={}", std::process::id());
    if auto {
        println!("ADDITION test game: taking {} damage every second. Commands: hit, shoot, spend <n>, respawn, state, quit", damage());
        std::thread::spawn(|| loop {
            std::thread::sleep(std::time::Duration::from_secs(1));
            let p = player();
            unsafe {
                let h = std::ptr::read_volatile(&p.health);
                std::ptr::write_volatile(&mut p.health, (h - damage()).max(0));
            }
            println!("{}", state());
        });
    }
    let _ = std::io::stdout().flush();

    let stdin = std::io::stdin();
    for line in stdin.lock().lines() {
        let Ok(line) = line else { break };
        let mut parts = line.split_whitespace();
        let p = player();
        let out = match parts.next() {
            Some("hit") => unsafe {
                let h = std::ptr::read_volatile(&p.health);
                std::ptr::write_volatile(&mut p.health, h - damage());
                state()
            },
            Some("shoot") => unsafe {
                let a = std::ptr::read_volatile(&p.ammo);
                std::ptr::write_volatile(&mut p.ammo, a - 1);
                state()
            },
            Some("spend") => unsafe {
                let n: i64 = parts.next().and_then(|n| n.parse().ok()).unwrap_or(10);
                let g = std::ptr::read_volatile(&p.gold);
                std::ptr::write_volatile(&mut p.gold, g - n);
                state()
            },
            Some("respawn") => {
                // New player object at a new heap address, like a level reload.
                world().player = new_player();
                state()
            }
            Some("state") => state(),
            Some("addrs") => addresses(),
            Some("quit") => break,
            Some(other) => format!("unknown command '{other}'"),
            None => continue,
        };
        println!("{out}");
        let _ = std::io::stdout().flush();
    }
}
